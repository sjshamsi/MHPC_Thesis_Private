TORCHRUN = """
srun python -u `which torchrun` \\
    --nnodes=$SLURM_JOB_NUM_NODES \\
    --nproc_per_node=$SLURM_GPUS_PER_NODE \\
    --rdzv_id=$SLURM_JOB_ID \\
    --rdzv_backend=c10d \\
    --rdzv_endpoint=$SLURMD_NODENAME:29500 \\
        train.py \\
            hydra.run.dir=outputs/\\${{now:%Y-%m-%d}}/$SLURM_JOB_ID \\
{overrides}
"""


def render_script(
    job_name: str,
    time: str,
    description: str,
    generator: str,
    overrides: List[str],
    pre_train: str = "",
    post_train: str = "",
) -> str:
    """Full sbatch script. `overrides` are Hydra CLI overrides, one per line."""
    header = SBATCH_HEADER.format(
        job_name=job_name,
        time=time,
        experiment_dir=EXPERIMENT_DIR,
        description=description,
        generator=generator,
        venv_activate=VENV_ACTIVATE,
        walrus_dir=WALRUS_DIR,
    )
    lines = " \\\n".join(f"            {o}" for o in overrides)
    return header + pre_train + TORCHRUN.format(overrides=lines) + post_train


def write_script(script_dir: str, filename: str, job_name: str, body: str) -> str:
    path = os.path.join(script_dir, filename)
    with open(path, "w") as f:
        f.write(body)
    os.chmod(path, 0o755)
    # SLURM will not create the per-job log directory itself.
    os.makedirs(os.path.join(EXPERIMENT_DIR, "slurm", job_name), exist_ok=True)
    return path


def write_run_all(
    script_dir: str, filename: str, lines: List[str], datasets: Sequence[str] = ()
) -> str:
    """Submit wrapper that runs the data preflight first and aborts if it fails.

    `datasets` narrows the file check (default: all nine) for runs that read a subset.
    """
    path = os.path.join(script_dir, filename)
    with open(path, "w") as f:
        f.write(
            "#!/bin/bash -l\n"
            "set -euo pipefail\n"
            'cd "$(dirname "$0")"\n'
            "module purge\n"
            "module load python\n"
            "module load cuda/12.2\n"
            f"source {VENV_ACTIVATE}\n"
            "# Refuse to submit until every file these runs read opens and the config composes.\n"
            f"python preflight_pt9.py {' '.join(datasets)}".rstrip()
            + "\n"
            + "\n".join(lines)
            + "\n"
        )
    os.chmod(path, 0o755)
    return path
