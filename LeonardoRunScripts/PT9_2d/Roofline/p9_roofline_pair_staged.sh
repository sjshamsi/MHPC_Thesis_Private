#!/bin/bash -l
#SBATCH --job-name=p9_roofline_pairGSPS_staged_H464_L10_M1120_E3_dw10
#SBATCH --time=06:00:00
#SBATCH --partition=boost_usr_prod
#SBATCH --qos=normal
#SBATCH --account=ICT26_MHPC_0
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --gpus-per-node=4
#SBATCH --cpus-per-gpu=8
#SBATCH --mem=0
#SBATCH --exclusive
#SBATCH --output=/leonardo_scratch/fast/ICT26_MHPC/sshamsi/logs/slurm/p9_roofline_pairGSPS_staged_H464_L10_M1120_E3_dw10/%j.out
#SBATCH --error=/leonardo_scratch/fast/ICT26_MHPC/sshamsi/logs/slurm/p9_roofline_pairGSPS_staged_H464_L10_M1120_E3_dw10/%j.err

# SCALING_STRATEGY_2D.md 5.2, paired staging test, staged arm: roofline-small shape
# on gray_scott + planetswe only. Compare only with the other arm of the pair.
# Generated by PT9_2d/Roofline/gen_pt9_roofline_runs.py -- do not hand-edit, regenerate instead.

set -euo pipefail

export OMP_NUM_THREADS=${SLURM_CPUS_ON_NODE}
export HDF5_USE_FILE_LOCKING=FALSE
export HYDRA_FULL_ERROR=1
export NCCL_DEBUG=WARN
export WANDB_MODE=offline
export WANDB_DIR=/leonardo_scratch/fast/ICT26_MHPC/sshamsi/logs
export AUTO_RESUME=${AUTO_RESUME:-True}

module purge
module load python
module load cuda/12.2
source /leonardo_work/ICT26_MHPC_0/sshamsi/pyenvs/env1/bin/activate

cd /leonardo/home/userexternal/sshamsi0/MHPC_Thesis/walrus

SRC=/leonardo_work/ICT26_MHPC_0/sshamsi/datasets
STAGE_DIR=/scratch_local/${SLURM_JOB_ID}/datasets
DATASETS=(gray_scott_reaction_diffusion planetswe)
# Remove the staged copy however the job ends, including on failure under set -e.
trap 'rm -rf "/scratch_local/${SLURM_JOB_ID}"' EXIT

# Abort cleanly, rather than filling the node disk, if the pair does not fit.
NEEDED=$(du -sb "${DATASETS[@]/#/$SRC/}" | awk '{s += $1} END {print s}')
mkdir -p "$STAGE_DIR"
AVAILABLE=$(df -B1 --output=avail "$STAGE_DIR" | tail -1)
echo "Staging needs $((NEEDED / 1024**3)) GiB; /scratch_local has $((AVAILABLE / 1024**3)) GiB free"
if (( NEEDED * 11 / 10 > AVAILABLE )); then
    echo "Not enough node-local space for the paired staging test; aborting." >&2
    exit 1
fi

STAGE_START=$(date +%s)
pids=()
for d in "${DATASETS[@]}"; do
    cp -r "$SRC/$d" "$STAGE_DIR/$d" &
    pids+=($!)
done
# Wait on each copy by PID: a bare `wait` returns 0 even if a copy failed, which would
# let training run on a half-staged dataset.
for p in "${pids[@]}"; do
    wait "$p"
done
STAGE_END=$(date +%s)
# Exclude this from the sec/epoch comparison: it is paid once, not per epoch.
echo "STAGING_SECONDS: $((STAGE_END - STAGE_START))"
du -sh "$STAGE_DIR"

srun python -u `which torchrun` \
    --nnodes=$SLURM_JOB_NUM_NODES \
    --nproc_per_node=$SLURM_GPUS_PER_NODE \
    --rdzv_id=$SLURM_JOB_ID \
    --rdzv_backend=c10d \
    --rdzv_endpoint=$SLURMD_NODENAME:29500 \
        train.py \
            hydra.run.dir=outputs/\${now:%Y-%m-%d}/$SLURM_JOB_ID \
            distribution=fsdp \
            model=isotropic_model \
            trainer=defaults \
            server=leonardo \
            data=Leonardo_pretrain9_2d \
            data/field_index_map_override=full_well_field_index \
            optimizer=adam \
            optimizer.lr=2.e-4 \
            trainer.enable_amp=False \
            trainer.grad_acc_steps=4 \
            trainer.clip_gradient=10 \
            trainer.prediction_type=delta \
            data.module_parameters.batch_size=2 \
            data.module_parameters.n_steps_input=6 \
            data.module_parameters.n_steps_output=1 \
            data.module_parameters.min_dt_stride=1 \
            data.module_parameters.max_dt_stride=5 \
            data.module_parameters.max_samples=2000 \
            model.projection_dim=48 \
            model.intermediate_dim=352 \
            model.groups=16 \
            model.override_dimensionality=3 \
            model.drop_path=0.05 \
            model/processor/space_mixing=full_spatial_attention \
            model.processor.space_mixing.num_heads=16 \
            model.processor.time_mixing.num_heads=16 \
            model.causal_in_time=True \
            model.jitter_patches=True \
            ++model.use_periodic_fixed_jitter=True \
            ++model.input_field_drop=0.0 \
            lr_scheduler=inv_sqrt_w_sqrt_ramps \
            trainer.short_validation_length=20 \
            trainer.val_frequency=2 \
            trainer.rollout_val_frequency=5 \
            trainer.max_rollout_steps=60 \
            trainer.video_validation=False \
            ++trainer.skip_spectral_metrics=True \
            ++trainer.debug_mode=True \
            checkpoint=defaults \
            experiment=defaults \
            finetuning_mods=defaults \
            ++experiment_dir=/leonardo_scratch/fast/ICT26_MHPC/sshamsi/logs \
            model.hidden_dim=464 \
            model.processor_blocks=10 \
            model.processor.space_mixing.mlp_dim=1120 \
            model.gradient_checkpointing_freq=0 \
            name=p9_roofline_pairGSPS_staged_H464_L10_M1120_E3_dw10 \
            logger.wandb_project_name="p9_roofline" \
            trainer.log_interval=10 \
            trainer.max_epoch=3 \
            data_workers=10 \
            auto_resume=$AUTO_RESUME \
            '~data.module_parameters.well_dataset_info.acoustic_scattering_discontinuous' \
            '~data.module_parameters.well_dataset_info.acoustic_scattering_inclusions' \
            '~data.module_parameters.well_dataset_info.acoustic_scattering_maze' \
            '~data.module_parameters.well_dataset_info.euler_multi_quadrants_openBC' \
            '~data.module_parameters.well_dataset_info.euler_multi_quadrants_periodicBC' \
            '~data.module_parameters.well_dataset_info.rayleigh_benard' \
            '~data.module_parameters.well_dataset_info.shear_flow' \
            data.well_base_path="$STAGE_DIR/"
