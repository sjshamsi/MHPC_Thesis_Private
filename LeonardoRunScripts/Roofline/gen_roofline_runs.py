"""
Generate the SCALING_STRATEGY.md 5.2 roofline runs. This helps us figure out if the costs are FLOP-proportional or dataloader-bound as the model parameter number changes. This is the GATE A experiment that unblocks everything past Tier 0 in the strategy document. If the runs are dataloader-bound as the model size decreases, then this is an issue because we cannot hope to have smaller costs for smaller models.

We make runs for four model sizes (fullDims, 200M, and roofline small) x 3 epochs each at N1, using data=Leonardo_smallest7_2d, batch_size=2, grad_acc_steps=4, etc.) so these points are comparable to all our other runs and the only thing chnages are the model dimensions and the number of data_workers. The 6th point -- staging the 7-dataset mixture to node-local scratch -- has
genuinely different script logic (a staging loop, not just parameter substitution) and
is hand-written as roofline_staged.sh instead, mirroring storage_bench_walrus.sh.

Also the first live-GPU exercise of the flopcount branch's FlopAccountant and seed_all:
after the first job lands, check its log for `flops_per_microbatch`/`cumulative_flops`
in the per-epoch W&B log before letting the rest run unattended.

Note `roofline_run_1.sh` (the 200M-anchor point) is a short 3-epoch wall-clock probe --
it answers GATE A (is cost FLOP-proportional?), not "where does this shape's loss
saturate?". It is NOT §7.0's saturation pilot; that role belongs to
`noise_floor_run_0.sh` (gen_noise_floor_runs.py), which runs the same shape far longer
specifically to read a loss curve off it. Do not conflate the two.

Usage:
    python gen_roofline_runs.py
    ./submit.sh roofline_run_0.sh   # submit one at a time (recommended: watch the
                                     # first one before firing the rest)
    bash run_roofline_all.sh        # or submit every generated job at once
"""

import os
from typing import Any, Dict, List

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

EXPERIMENT_DIR = "/leonardo_scratch/fast/ICT26_MHPC/sshamsi/logs"
WALRUS_DIR = "/leonardo/home/userexternal/sshamsi0/MHPC_Thesis/walrus"
VENV_ACTIVATE = "/leonardo_work/ICT26_MHPC_0/sshamsi/pyenvs/env1/bin/activate"
WANDB_PROJECT = "walrus_leonardo_roofline"

# SCALING_STRATEGY.md §2.3 / §5.2. mlp is pinned explicitly for all three even where
# it equals the 4*hidden_dim default (fullDims), so the template needs no special case.
SHAPES: List[Dict[str, Any]] = [
    {"tag": "fullDims", "hidden_dim": 1408, "depth": 40, "mlp": 5632, "gc_freq": 2, "time": "08:00:00"},
    {"tag": "200Manchor", "hidden_dim": 768, "depth": 12, "mlp": 2048, "gc_freq": 0, "time": "04:00:00"},
    {"tag": "small", "hidden_dim": 464, "depth": 10, "mlp": 1120, "gc_freq": 0, "time": "04:00:00"},
]

# data_workers ∈ {8, 10, 16} at the smallest shape only (§5.2); 10 is that shape's own
# base run above, so only the other two are separate jobs.
SMALL_SHAPE_DW_VARIANTS = [8, 16]
BASE_DATA_WORKERS = 10

EPOCHS = 3
HEADS = 16

# model.override_dimensionality=3 -> include_d=[3]: exactly one encoder/decoder pair.
# Must be >0 (=0 builds a second, never-trained pair) and must be 3, not 2: forward()
# takes its dim_key from metadata.n_spatial_dims, which the datamodule has already set to
# 3 for every dataset (inflated_dataset.py, pad_cartesian_data_to_d), so =2 dies with
# KeyError '3'. The '2'/'3' keys are bucket labels, not shapes -- both pairs are built
# with spatial_dims=3 -- so on this 2D-only mixture =3 is bit-identical to a working =2.
# GUARDRAIL: only valid while the mixture is single-dimensionality. Adding a 3D dataset
# would silently share one encoder across both dimensionalities rather than crashing;
# that case needs =0, which dispatches on the actual tensor shape.
SBATCH_TEMPLATE = """#!/bin/bash -l
#SBATCH --job-name={job_name}
#SBATCH --time={time}
#SBATCH --partition=boost_usr_prod
#SBATCH --qos=normal
#SBATCH --account=ICT26_MHPC_0
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --gpus-per-node=4
#SBATCH --cpus-per-gpu=8
#SBATCH --mem=0
#SBATCH --exclusive
#SBATCH --output={experiment_dir}/slurm/{job_name}/%j.out
#SBATCH --error={experiment_dir}/slurm/{job_name}/%j.err

# SCALING_STRATEGY.md 5.2 (GATE A): shape {hidden_dim}/{depth}/{mlp}, {epochs} epochs,
# data_workers={data_workers}. Fits into sec/epoch = a + b*FLOPs across the family
# generated by gen_roofline_runs.py -- do not hand-edit, regenerate instead.

set -euo pipefail

export OMP_NUM_THREADS=${{SLURM_CPUS_ON_NODE}}
export HDF5_USE_FILE_LOCKING=FALSE
export HYDRA_FULL_ERROR=1
export NCCL_DEBUG=WARN
export WANDB_MODE=offline
export WANDB_DIR={experiment_dir}
export AUTO_RESUME=${{AUTO_RESUME:-True}}

module purge
module load python
module load cuda/12.2
source {venv_activate}

cd {walrus_dir}

srun python -u `which torchrun` \\
    --nnodes=$SLURM_JOB_NUM_NODES \\
    --nproc_per_node=$SLURM_GPUS_PER_NODE \\
    --rdzv_id=$SLURM_JOB_ID \\
    --rdzv_backend=c10d \\
    --rdzv_endpoint=$SLURMD_NODENAME:29500 \\
        train.py \\
            hydra.run.dir=outputs/\\${{now:%Y-%m-%d}}/$SLURM_JOB_ID \\
            distribution=fsdp \\
            model=isotropic_model \\
            name={job_name} \\
            trainer=defaults \\
            server=leonardo \\
            data=Leonardo_smallest7_2d \\
            data/field_index_map_override=full_well_field_index \\
            optimizer=adam \\
            optimizer.lr=2.e-4 \\
            logger.wandb_project_name="{wandb_project}" \\
            trainer.enable_amp=False \\
            trainer.grad_acc_steps=4 \\
            trainer.clip_gradient=10 \\
            trainer.prediction_type=delta \\
            trainer.log_interval=50 \\
            model.gradient_checkpointing_freq={gc_freq} \\
            data.module_parameters.batch_size=2 \\
            data.module_parameters.n_steps_input=6 \\
            data.module_parameters.n_steps_output=1 \\
            data.module_parameters.min_dt_stride=1 \\
            data.module_parameters.max_dt_stride=5 \\
            data.module_parameters.max_samples=2000 \\
            model.projection_dim=48 \\
            model.intermediate_dim=352 \\
            model.groups=16 \\
            model.override_dimensionality=3 \\
            model.hidden_dim={hidden_dim} \\
            model.processor_blocks={depth} \\
            model.drop_path=0.05 \\
            model/processor/space_mixing=full_spatial_attention \\
            model.processor.space_mixing.mlp_dim={mlp} \\
            model.processor.space_mixing.num_heads={heads} \\
            model.processor.time_mixing.num_heads={heads} \\
            model.causal_in_time=True \\
            model.jitter_patches=True \\
            seed=0 \\
            lr_scheduler=inv_sqrt_w_sqrt_ramps \\
            trainer.short_validation_length=20 \\
            trainer.val_frequency=2 \\
            trainer.rollout_val_frequency=5 \\
            trainer.max_rollout_steps=60 \\
            trainer.video_validation=False \\
            trainer.max_epoch={epochs} \\
            data_workers={data_workers} \\
            auto_resume=$AUTO_RESUME \\
            checkpoint=defaults \\
            experiment=defaults \\
            finetuning_mods=defaults \\
            ++trainer.skip_spectral_metrics=True \\
            ++experiment_dir={experiment_dir}
"""


def render(tag, hidden_dim, depth, mlp, gc_freq, time, data_workers):
    job_name = f"roofline_{tag}_H{hidden_dim}_L{depth}_M{mlp}_E{EPOCHS}_dw{data_workers}"
    return job_name, SBATCH_TEMPLATE.format(
        job_name=job_name,
        time=time,
        experiment_dir=EXPERIMENT_DIR,
        venv_activate=VENV_ACTIVATE,
        walrus_dir=WALRUS_DIR,
        wandb_project=WANDB_PROJECT,
        hidden_dim=hidden_dim,
        depth=depth,
        mlp=mlp,
        gc_freq=gc_freq,
        heads=HEADS,
        epochs=EPOCHS,
        data_workers=data_workers,
    )


def write_script(job_name, body, index):
    script_path = os.path.join(SCRIPT_DIR, f"roofline_run_{index}.sh")
    with open(script_path, "w") as f:
        f.write(body)
    os.chmod(script_path, 0o755)
    os.makedirs(os.path.join(EXPERIMENT_DIR, "slurm", job_name), exist_ok=True)
    return script_path


def main():
    submissions = []
    index = 0

    for shape in SHAPES:
        job_name, body = render(data_workers=BASE_DATA_WORKERS, **shape)
        write_script(job_name, body, index)
        submissions.append(f"./submit.sh roofline_run_{index}.sh")
        index += 1

    small = next(s for s in SHAPES if s["tag"] == "small")
    for dw in SMALL_SHAPE_DW_VARIANTS:
        job_name, body = render(data_workers=dw, **small)
        write_script(job_name, body, index)
        submissions.append(f"./submit.sh roofline_run_{index}.sh")
        index += 1

    # roofline_staged.sh reads the same 8-dataset mixture from $WORK as every job
    # above, over the network filesystem, concurrently -- running it at the same time
    # as the others adds I/O contention that the un-staged points don't otherwise see,
    # which would bias exactly the staged-vs-unstaged comparison this point exists to
    # make. Listed last and commented out here; submit it once the others have started
    # or finished, not in the same burst.
    run_all_path = os.path.join(SCRIPT_DIR, "run_roofline_all.sh")
    with open(run_all_path, "w") as f:
        f.write(
            "#!/bin/bash\n"
            + "\n".join(submissions)
            + "\n\n# Submit separately (see comment above) -- do not uncomment into the same burst:\n"
            + "# ./submit.sh roofline_staged.sh\n"
        )
    os.chmod(run_all_path, 0o755)

    print(f"Generated {index} roofline_run_N.sh scripts + run_roofline_all.sh in {SCRIPT_DIR}")
    print("The 6th roofline point (node-local staging) is hand-written: roofline_staged.sh")


if __name__ == "__main__":
    main()
