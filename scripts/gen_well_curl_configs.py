"""Write curl config files for downloading The Well datasets through a CINECA data mover.

The data movers (data.leonardo.cineca.it) have no Python and no shell -- only curl, wget,
rsync, ... -- so the_well's own downloader (and download_the_well_datasets.py, which wraps it)
cannot run there. This script does the Python half on the login node instead: it reads
the_well's URL registry and writes one curl config per dataset (`url =` / `output =` pairs with
absolute paths, since $WORK and ~ are undefined on a data mover). The transfer itself is then
a single `curl --config <file>` run on the data mover; see download_well_via_datamover.sh.

Output layout is identical to the_well's downloader, i.e. what walrus's
`data.well_base_path` expects:
    <base-path>/datasets/<dataset>/stats.yaml
    <base-path>/datasets/<dataset>/data/<split>/*.hdf5

It also HEAD-requests every file and writes `manifest.tsv` (expected byte size per file), so
`--verify` can check a finished download by stat-ing exactly the listed paths -- no `du`,
`find` or `ls -R` over the Lustre tree (CINECA Lustre best practice: avoid metadata-heavy
recursive commands).

Usage (login node, env1 venv active):
    python gen_well_curl_configs.py                 # write configs + manifest
    python gen_well_curl_configs.py --verify        # after downloading: check sizes
"""

import argparse
import concurrent.futures
import os
import sys
import sysconfig
import urllib.request

import yaml

DEFAULT_BASE_PATH = "/leonardo_work/ICT26_MHPC_0/sshamsi"
DEFAULT_OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "well_curl_configs")
# Located without importing the_well (its __init__ pulls in torch, which is slow on Lustre).
DEFAULT_REGISTRY = os.path.join(
    sysconfig.get_paths()["purelib"], "the_well", "utils", "registry.yaml"
)

DATASETS = [
    "rayleigh_taylor_instability",
    "acoustic_scattering_inclusions",
    "acoustic_scattering_maze",
    "rayleigh_benard",
    "shear_flow",
    "turbulent_radiative_layer_3D",
    "supernova_explosion_128",  # the variant walrus's all_2_3d.yaml mixture uses
    "turbulence_gravity_cooling",
    "euler_multi_quadrants_periodicBC",
    "euler_multi_quadrants_openBC",
]
SPLITS = ["train", "valid", "test"]


def parse_args():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--base-path", default=DEFAULT_BASE_PATH)
    parser.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    parser.add_argument("--registry", default=DEFAULT_REGISTRY)
    parser.add_argument("--dataset", nargs="+", default=DATASETS, metavar="NAME")
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Check downloaded file sizes against manifest.tsv instead of writing configs.",
    )
    return parser.parse_args()


def file_list(registry, base_path, dataset):
    """(split, url, absolute output path) for every file of a dataset, stats.yaml first."""
    ds_dir = os.path.join(base_path, "datasets", dataset)
    entries = [("stats", registry[dataset]["stats"], os.path.join(ds_dir, "stats.yaml"))]
    for split in SPLITS:
        for url in registry[dataset][split]:
            out = os.path.join(ds_dir, "data", split, os.path.basename(url))
            entries.append((split, url, out))
    return entries


def head_size(url, retries=3):
    """Content-Length of url, and whether the server advertises byte ranges (needed to resume)."""
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, method="HEAD")
            with urllib.request.urlopen(req, timeout=60) as resp:
                size = int(resp.headers["Content-Length"])
                ranges = resp.headers.get("Accept-Ranges", "") == "bytes"
                return size, ranges
        except Exception:
            if attempt == retries - 1:
                raise


def write_configs(args, registry):
    os.makedirs(args.out_dir, exist_ok=True)
    rows = []
    for dataset in args.dataset:
        entries = file_list(registry, args.base_path, dataset)
        with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
            heads = list(pool.map(head_size, [url for _, url, _ in entries]))

        total = sum(size for size, _ in heads)
        no_ranges = [url for (_, url, _), (_, ranges) in zip(entries, heads) if not ranges]
        cfg_path = os.path.join(args.out_dir, f"{dataset}.cfg")
        with open(cfg_path, "w") as f:
            f.write(
                "# Generated by scripts/gen_well_curl_configs.py -- regenerate, don't hand-edit.\n"
                f"# {dataset}: {len(entries)} files, {total / 1e9:.1f} GB\n"
                "# Run on the data mover via scripts/download_well_via_datamover.sh.\n"
            )
            for (_, url, out), (size, _) in zip(entries, heads):
                f.write(f'\n# {size / 1e9:.2f} GB\nurl = "{url}"\noutput = "{out}"\n')
        for (split, _, out), (size, _) in zip(entries, heads):
            rows.append((dataset, split, out, size))

        largest = max(size for size, _ in heads)
        print(
            f"{dataset:34s} {len(entries):4d} files  {total / 1e9:8.1f} GB  "
            f"largest {largest / 1e9:6.1f} GB  -> {cfg_path}"
        )
        if no_ranges:
            print(f"  WARNING: {len(no_ranges)} file(s) without Accept-Ranges; resume may restart them")

    manifest = os.path.join(args.out_dir, "manifest.tsv")
    with open(manifest, "w") as f:
        f.write("dataset\tsplit\tpath\tbytes\n")
        for row in rows:
            f.write("\t".join(map(str, row)) + "\n")
    grand = sum(r[3] for r in rows)
    print(f"\nTotal: {len(rows)} files, {grand / 1e12:.2f} TB.  Manifest: {manifest}")


def verify(args):
    manifest = os.path.join(args.out_dir, "manifest.tsv")
    with open(manifest) as f:
        next(f)
        rows = [line.rstrip("\n").split("\t") for line in f]
    status = {}
    for dataset, _, path, expected in rows:
        if dataset not in args.dataset:
            continue
        try:
            actual = os.stat(path).st_size
        except FileNotFoundError:
            actual = None
        ok, missing, wrong = status.setdefault(dataset, [0, [], []])
        if actual is None:
            missing.append(path)
        elif actual != int(expected):
            wrong.append((path, actual, int(expected)))
        else:
            status[dataset][0] += 1
    all_ok = True
    for dataset, (ok, missing, wrong) in status.items():
        verdict = "OK" if not missing and not wrong else "INCOMPLETE"
        all_ok &= verdict == "OK"
        print(f"{dataset:34s} {verdict:10s} {ok} ok, {len(missing)} missing, {len(wrong)} wrong size")
        for path in missing[:5]:
            print(f"    missing: {path}")
        for path, actual, expected in wrong[:5]:
            print(f"    size {actual} != {expected}: {path}")
    sys.exit(0 if all_ok else 1)


def main():
    args = parse_args()
    if args.verify:
        verify(args)
        return
    with open(args.registry) as f:
        registry = yaml.safe_load(f)
    unknown = sorted(set(args.dataset) - set(registry))
    if unknown:
        sys.exit(f"Not in the_well registry: {unknown}")
    write_configs(args, registry)


if __name__ == "__main__":
    main()
